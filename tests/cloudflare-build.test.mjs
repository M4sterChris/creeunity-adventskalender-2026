import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, readdir, rm } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { prepareCloudflare } from '../tools/prepare-cloudflare.mjs';

test('Cloudflare build isolates private SQL from assets and requires worker-first routing', async t => {
  const qa = resolve('.qa'); await mkdir(qa, { recursive: true });
  const root = await mkdtemp(resolve(qa, 'cloudflare-build-'));
  t.after(async () => { assert.ok(root.startsWith(qa + sep)); await rm(root, { recursive: true, force: true }); });
  const source = resolve(root, 'private');
  await mkdir(resolve(source, 'images'), { recursive: true });
  await mkdir(resolve(source, 'audio'), { recursive: true });
  await mkdir(resolve(root, 'assets/released'), { recursive: true });
  for (const file of ['index.html', 'styles.css', 'script.js', 'theme.js', 'github-editor.js', 'text-format.js', 'puzzles.js', 'puzzle-client.js', 'media.js']) await writeFile(resolve(root, file), 'PUBLIC');
  await writeFile(resolve(root, 'assets/placeholder.svg'), 'PUBLIC');
  await writeFile(resolve(root, 'assets/released/stale-private-file.json'), 'NEVER-COPY-THIS');
  await writeFile(resolve(source, 'images/door.png'), 'PNG');
  await writeFile(resolve(source, 'audio/door.mp3'), 'MP3');
  const config = JSON.parse(await readFile(new URL('../examples/doors-data.example.json', import.meta.url), 'utf8'));
  for (const door of config.doors) door.image = './images/door.png';
  config.doors[0].puzzle = { type: 'number', answer: '042', fragment: "SECRET-REWARD'S" };
  config.doors[0].audio = './audio/door.mp3';
  await writeFile(resolve(source, 'doors-data.json'), JSON.stringify(config));
  const out = resolve(root, '.cloudflare-build');
  const build = await prepareCloudflare({ root, source, out });
  const settings = JSON.parse(await readFile(build.config, 'utf8'));
  assert.equal(settings.assets.run_worker_first, true);
  assert.equal(settings.preview_urls, false);
  assert.equal(settings.d1_databases[0].jurisdiction, 'eu');
  assert.equal(settings.observability.enabled, false);
  const names = await readdir(build.assets, { recursive: true });
  assert.ok(!names.some(name => /\.json$|\.sql$|\.env|private|released/.test(name)));
  assert.equal(build.mediaFiles, 2);
  assert.ok((await readFile(build.seed, 'utf8')).includes("SECRET-REWARD''S"));
  assert.ok((await readFile(build.seed, 'utf8')).includes('INSERT INTO asset_sizes'));
  for (const file of names.filter(name => /\.(?:js|css|html|svg)$/.test(name))) assert.ok(!(await readFile(resolve(build.assets, file), 'utf8')).includes('SECRET-REWARD'));
  await assert.rejects(prepareCloudflare({ root, source, out: resolve(root, '..') }), /isolated/);
});
